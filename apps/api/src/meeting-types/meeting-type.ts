// Тип встречи из спецификации §6 (docs/spec/calendar.md):
// шаблон, заданный владельцем, — размер слота и подпись на гостевой странице.
export interface MeetingType {
  /** Внешний идентификатор: задаёт владелец, уникален и не меняется. */
  id: string
  /** Название на карточке для гостя. */
  title: string
  /** Описание для гостя; если не задано — null. */
  description: string | null
  /** Длительность в минутах: от 30 до 240, кратна 30. */
  durationMinutes: number
}
